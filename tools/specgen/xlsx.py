"""spec -> Requirements_Catalogue.xlsx, RTM.xlsx, Test_Plan.xlsx in docs/generated/ (same sheets and layout as v0.9).

On request only (python tools/build_all.py --xlsx); the output folder is git-ignored.
"""
from __future__ import annotations

from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation

from . import DOCS_DIR
from .tables import (
    functional_rows,
    non_functional_rows,
    open_item_rows,
    rtm_rows,
    strategy_rows,
    test_case_rows,
    test_to_req_rows,
)

NAVY = "FF1F4E8C"
BAND = "FFF3F6FA"
YELLOW = "FFFFF2CC"
HEAD_FONT = Font(bold=True, size=10, color="FFFFFFFF")
HEAD_FILL = PatternFill("solid", fgColor=NAVY)
BAND_FILL = PatternFill("solid", fgColor=BAND)
EDIT_FILL = PatternFill("solid", fgColor=YELLOW)
TOP_WRAP = Alignment(wrap_text=True, vertical="top")


def _banner(meta) -> list[str]:
    return [f"Project: {meta['title']} (working name {meta['code_name']})",
            f"Document version {meta['version']}, 16 October 2026 - Draft for project-guide review.",
            "Generated from the same data definition as the Project Design Specification, the RTM and the test plan, "
            "so all IDs match."]


def readme_sheet(wb, title, lines):
    ws = wb.active
    ws.title = "README"
    ws.column_dimensions["A"].width = 120
    ws["A1"] = title
    ws["A1"].font = Font(bold=True, size=14, color=NAVY)
    for i, line in enumerate(lines, start=2):
        if line is not None:
            ws.cell(row=i, column=1, value=line)


def table_sheet(wb, name, hdr, rows, widths, editable=(), validation=None):
    ws = wb.create_sheet(name)
    ws.append(hdr)
    for r in rows:
        ws.append([v if v != "" else None for v in r])
    for c in ws[1]:
        c.font, c.fill, c.alignment = HEAD_FONT, HEAD_FILL, TOP_WRAP
    for i, row in enumerate(ws.iter_rows(min_row=2), start=2):
        for c in row:
            c.alignment = TOP_WRAP
            if c.column_letter in editable:
                c.fill = EDIT_FILL
            elif i % 2 == 1:
                c.fill = BAND_FILL
    for col, w in widths.items():
        ws.column_dimensions[col].width = w
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = f"A1:{get_column_letter(len(hdr))}{len(rows) + 1}"
    if validation:
        col, choices = validation
        dv = DataValidation(type="list", formula1='"' + ",".join(choices) + '"', allow_blank=True)
        dv.add(f"{col}2:{col}{len(rows) + 1}")
        ws.add_data_validation(dv)
    return ws


def summary_header(ws, row, cols):
    for i, h in enumerate(cols, start=1):
        c = ws.cell(row=row, column=i, value=h)
        c.font, c.fill = HEAD_FONT, HEAD_FILL


def requirements_catalogue(spec):
    wb = Workbook()
    readme_sheet(wb, "ResLand - Requirements Catalogue (Deliverable B)", [None, *_banner(spec["meta"]), None,
        "Sheets:",
        "Functional - all functional requirements with ID, description, category, rationale, priority, input, output, "
        "module, design element, verification, acceptance criterion, tests and paper source.",
        "Non_Functional - non-functional requirements; performance figures are proposed targets requiring "
        "confirmation.",
        "Open_Items - details missing or ambiguous in the paper; referenced as OI-xx from requirements marked TBC.",
        "Summary - counts by group and priority (formulas; update automatically if rows change).", None,
        "Conventions:",
        "Priority uses MoSCoW (Must / Should / Could). Verification: Test, Inspection, Analysis, Demonstration.",
        "'Proposed implementation decision' in the Source column means the paper does not specify the item; the value "
        "is a design choice to be confirmed.",
        "Status column (yellow) is for the team to update during implementation: Proposed / Implemented / Verified.",
        "Generated by tools/build_all.py from spec/spec_data.py - edit the spec, not this file."])
    hdr, rows = functional_rows(spec)
    n_fr = len(rows)
    table_sheet(wb, "Functional", hdr, rows,
                dict(A=12, B=20, C=55, D=35, E=9, F=22, G=24, H=9, I=24, J=13, K=50, L=14, M=26, N=12),
                editable="N", validation=("N", ["Proposed", "Implemented", "Verified"]))
    hdr, rows = non_functional_rows(spec)
    n_nfr = len(rows)
    table_sheet(wb, "Non_Functional", hdr, rows, dict(A=14, B=15, C=55, D=35, E=9, F=45, G=16, H=14, I=30))
    hdr, rows = open_item_rows(spec)
    n_oi = len(rows)
    table_sheet(wb, "Open_Items", hdr, rows, dict(A=8, B=70, C=30, D=55))

    ws = wb.create_sheet("Summary")
    ws["A1"] = "Functional requirements by group"
    ws["A1"].font = Font(bold=True, size=12, color=NAVY)
    summary_header(ws, 2, ["Group", "Category", "Count", "Must", "Should", "Could"])
    rng_b, rng_e = f"Functional!$B$2:$B${n_fr + 1}", f"Functional!$E$2:$E${n_fr + 1}"
    groups = spec["tables"]["fr_groups"]
    for i, g in enumerate(groups, start=3):
        ws.append([g["Group"], g["Area"], f"=COUNTIF({rng_b},B{i})",
                   *[f'=COUNTIFS({rng_b},$B{i},{rng_e},"{p}")' for p in ("Must", "Should", "Could")]])
    last = 2 + len(groups)
    ws.append(["Total", None, *[f"=SUM({c}3:{c}{last})" for c in "CDEF"]])
    ws.append([None])
    ws.append(["Non-functional requirements", None, f"=COUNTA(Non_Functional!A2:A{n_nfr + 1})"])
    ws.append(["Open items", None, f"=COUNTA(Open_Items!A2:A{n_oi + 1})"])
    ws.append(["Requirements without a test case", None, f"=COUNTBLANK(Functional!L2:L{n_fr + 1})"])
    for col, w in dict(A=14, B=40, C=10).items():
        ws.column_dimensions[col].width = w
    return wb


def rtm_workbook(spec):
    wb = Workbook()
    readme_sheet(wb, "ResLand - Requirements Traceability Matrix (Deliverable E)", [None, *_banner(spec["meta"]), None,
        "Sheets:",
        "RTM - forward traceability: requirement -> design component -> diagram -> implementation module -> test "
        "cases -> acceptance criterion -> status.",
        "Test_to_Req - backward traceability: every test case and the requirements it verifies.",
        "Coverage - formula-based checks (requirements without tests, tests per level).", None,
        "Status values: Proposed (design stage), Implemented, Verified. Update the yellow Status column as work "
        "progresses; RT-03 runs tools/rtm_check.py in CI.",
        "Generated by tools/build_all.py from spec/spec_data.py - edit the spec, not this file."])
    hdr, rows = rtm_rows(spec)
    n = len(rows) + 1
    table_sheet(wb, "RTM", hdr, rows, dict(A=14, B=55, C=22, D=9, E=30, F=14, G=34, H=16, I=13, J=50, K=12),
                editable="K", validation=("K", ["Proposed", "Implemented", "Verified"]))
    hdr, rows = test_to_req_rows(spec)
    nt = len(rows) + 1
    table_sheet(wb, "Test_to_Req", hdr, rows, dict(A=10, B=22, C=26, D=45, E=50))
    ws = wb.create_sheet("Coverage")
    ws["A1"] = "Coverage checks"
    ws["A1"].font = Font(bold=True, size=12, color=NAVY)
    ws.append([None])
    for label, f in [
        ("Requirements in RTM", f"=COUNTA(RTM!A2:A{n})"),
        ("Functional requirements", f'=COUNTIF(RTM!A2:A{n},"FR-*")'),
        ("Non-functional requirements", f'=COUNTIF(RTM!A2:A{n},"NFR-*")'),
        ("Requirements without test case", f"=COUNTBLANK(RTM!H2:H{n})"),
        ("Requirements without design component", f"=COUNTBLANK(RTM!E2:E{n})"),
        ("Requirements with status Verified", f'=COUNTIF(RTM!K2:K{n},"Verified")'),
        *[(f"Test cases - {lv}", f'=COUNTIF(Test_to_Req!B2:B{nt},"{lv}")')
          for lv in ("Unit", "Integration", "System", "Regression", "Experimental validation")],
    ]:
        ws.append([label, f])
    ws.column_dimensions["A"].width = 42
    ws.column_dimensions["B"].width = 12
    return wb


def test_plan_workbook(spec):
    wb = Workbook()
    readme_sheet(wb, "ResLand - Test Plan (Deliverable H)", [None, *_banner(spec["meta"]), None,
        "Status of all test cases: NOT EXECUTED. This is a design-stage plan; no result is claimed."
        if all(t["status"] == "Not executed" for t in spec["tests"]) else
        "Status column reflects tests actually executed; see Executed by / Date / Actual result.", None,
        "Test types:",
        "Software correctness (UT, IT, ST, RT): deterministic pass/fail; run in CI or at sprint end.",
        "Control-performance experiment (EV): measures how closely ResLand reproduces the paper; a deviation is "
        "investigated against the open items, not counted as a software failure.", None,
        "How to use:",
        "Test status is maintained in spec/spec_data.py (TESTS) and regenerated here; record Status, Executed by, "
        "Date, Actual result and Defect / notes there when a test is run. Status values: Not executed, Pass, Fail, "
        "Blocked.",
        "Summary sheet counts update automatically.",
        "Generated by tools/build_all.py from spec/spec_data.py - edit the spec, not this file."])
    hdr, rows = test_case_rows(spec)
    n = len(rows) + 1
    table_sheet(wb, "Test_Cases", hdr, rows,
                dict(A=9, B=14, C=20, D=30, E=22, F=28, G=40, I=30, J=13, L=11, M=30, N=22),
                editable="JKLMN", validation=("J", ["Not executed", "Pass", "Fail", "Blocked"]))
    hdr, rows = strategy_rows(spec)
    table_sheet(wb, "Strategy", hdr, rows, dict(A=20, B=45, C=30, D=22, E=14, F=26, G=30))
    ws = wb.create_sheet("Summary")
    ws["A1"] = "Execution summary (updates from Test_Cases)"
    ws["A1"].font = Font(bold=True, size=12, color=NAVY)
    summary_header(ws, 2, ["Level", "Total", "Not executed", "Pass", "Fail", "Blocked"])
    b, j_ = f"Test_Cases!$B$2:$B${n}", f"Test_Cases!$J$2:$J${n}"
    for i, lv in enumerate(["Unit", "Integration", "System", "Regression", "Experimental validation"], start=3):
        ws.append([lv, f"=COUNTIF({b},A{i})",
                   *[f'=COUNTIFS({b},$A{i},{j_},"{s}")' for s in ("Not executed", "Pass", "Fail", "Blocked")]])
    ws.append(["Total", *[f"=SUM({c}3:{c}7)" for c in "BCDEF"]])
    for col, w in dict(A=26, B=10, C=14, D=10).items():
        ws.column_dimensions[col].width = w
    return wb


def write_xlsx(spec) -> list[str]:
    out = []
    for name, fn in [("Requirements_Catalogue", requirements_catalogue), ("RTM", rtm_workbook),
                     ("Test_Plan", test_plan_workbook)]:
        out_dir = DOCS_DIR / "generated"
        out_dir.mkdir(exist_ok=True)
        path = out_dir / f"{name}.xlsx"
        fn(spec).save(path)
        out.append(f"docs/generated/{path.name}")
    return out
